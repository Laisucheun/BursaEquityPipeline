def get_sector(stock_code: str) -> str | None:
    """Return primary sector (e.g. 'Financials', 'Energy')."""
    entry = INDUSTRY_MAP.get(stock_code)
    return entry[1] if entry else None


def get_industry(stock_code: str) -> str | None:
    """Return industry group (e.g. 'Bank (Money Center)', 'Power')."""
    entry = INDUSTRY_MAP.get(stock_code)
    return entry[0] if entry else None


def get_profile(stock_code: str) -> tuple[frozenset[str], frozenset[str]]:
    """Return (expected_concepts, inapplicable_concepts) for a company."""
    industry = get_industry(stock_code)
    if industry is None:
        return _DEFAULT_PROFILE
    if industry in _BANK_INDUSTRIES:
        return (_BANK_EXPECTED, _BANK_INAPPLICABLE)
    if industry in _REIT_INDUSTRIES:
        return (_REIT_EXPECTED, _REIT_INAPPLICABLE)
    if industry in _INSURANCE_INDUSTRIES:
        return (_INSURANCE_EXPECTED, _INSURANCE_INAPPLICABLE)
    return _DEFAULT_PROFILE
