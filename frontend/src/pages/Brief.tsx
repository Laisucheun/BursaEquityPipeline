import { useState } from "react";
import { Link, useParams } from "react-router-dom";
import { api, type Brief as BriefData, type Deadline, type NewsBrief } from "../api";
import { Section } from "../components";
import { useAsync } from "../lib";

export const longDate = (iso: string) =>
  new Date(`${iso}T00:00:00`).toLocaleDateString("en-GB", { weekday: "long", day: "numeric", month: "long", year: "numeric" });
const shortDate = (iso: string) =>
  new Date(`${iso}T00:00:00`).toLocaleDateString("en-GB", { weekday: "short", day: "numeric", month: "short" });

// Only **bold** and [label](http(s)://...) are rendered; everything else is plain text.
const TOKEN = /\*\*(.+?)\*\*|\[([^\]]+)\]\((https?:\/\/[^\s)]+)\)/g;

export function Rich({ text }: { text: string }) {
  const out: React.ReactNode[] = [];
  let last = 0;
  for (const m of text.matchAll(TOKEN)) {
    const at = m.index ?? 0;
    if (at > last) out.push(text.slice(last, at));
    out.push(m[1] != null
      ? <strong key={at}><Rich text={m[1]} /></strong>
      : <a key={at} href={m[3]} target="_blank" rel="noopener noreferrer">{m[2]}</a>);
    last = at + m[0].length;
  }
  if (last < text.length) out.push(text.slice(last));
  return <>{out}</>;
}

const Bullets = ({ items }: { items: string[] }) => (
  <ul className="brief-list">{items.map((t, i) => <li key={i}><Rich text={t} /></li>)}</ul>
);

export default function Brief() {
  const { date } = useParams();
  const brief = useAsync(() => api.brief(date), [date]);
  return (
    <article className="report brief">
      <p style={{ marginTop: 0 }}><Link to="/feed">← Results feed</Link></p>
      <Section state={brief}>{(b) => <Body b={b} />}</Section>
    </article>
  );
}

function Body({ b }: { b: BriefData }) {
  const n = b.news;
  return (
    <>
      <div className="brief-nav">
        {b.previous_date ? <Link to={`/feed/brief/${b.previous_date}`}>← {shortDate(b.previous_date)}</Link> : <span />}
        {b.next_date ? <Link to={`/feed/brief/${b.next_date}`}>{shortDate(b.next_date)} →</Link> : <span />}
      </div>
      <h1>{n?.title ?? `Bursa Morning Brief: ${longDate(b.date)}`}</h1>

      {n ? <News n={n} /> : (
        <div className="notice" style={{ marginTop: 16 }}>
          {b.news_error ? "This day's brief could not be displayed." : "No brief for this day yet."}{" "}
          The filing calendar below is still current.
        </div>
      )}

      <h2 className="rh">What to watch</h2>
      <Bullets items={[...(n?.watch ?? []), ...b.calendar.watch]} />

      <h2 className="rh">Upcoming annual reports</h2>
      <AnnualReports items={b.calendar.annual_reports} days={b.calendar.days} />

      {b.calendar.calendar.length > 0 && (
        <>
          <h2 className="rh">Filing calendar</h2>
          <DeadlineTable rows={b.calendar.calendar} />
          <p className="muted small">Largest companies due in the next {b.calendar.days} days, annual and quarterly.</p>
        </>
      )}

      {n && n.sources.length > 0 && (
        <>
          <h2 className="rh">Sources</h2>
          <ol className="sources">
            {n.sources.map((s, i) => (
              <li key={i}>{/^https?:\/\//.test(s.url) ? <a href={s.url} target="_blank" rel="noopener noreferrer">{s.title}</a> : s.title}</li>
            ))}
          </ol>
        </>
      )}

      <p className="muted feed-foot">
        {n ? `Generated by Claude from public sources (${new Date(n.generated_at).toLocaleString("en-GB")}). ` : ""}
        May contain errors; not investment advice. Filing dates are Listing Requirements deadlines, not announcement dates.
      </p>
    </>
  );
}

function News({ n }: { n: NewsBrief }) {
  return (
    <>
      <h2 className="rh">TL;DR</h2>
      <Bullets items={n.tldr} />

      <h2 className="rh">Markets</h2>
      <div className="tablewrap">
        <table>
          <thead><tr><th>Asset</th><th className="num">{n.markets.as_of}</th><th className="num">Change</th></tr></thead>
          <tbody>
            {n.markets.rows.map((r) => (
              <tr key={r.asset}>
                <td>{r.asset}</td>
                <td className="num">{r.level}</td>
                <td className={`num ${r.change.trim().startsWith("-") || r.change.trim().startsWith("−") ? "bad" : r.change.trim().startsWith("+") ? "ok" : ""}`}>{r.change}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
      {n.markets.comment.length > 0 && <Bullets items={n.markets.comment} />}

      {n.sections.map((s) => (
        <div key={s.heading}>
          <h2 className="rh">{s.heading}</h2>
          {s.table && (
            <div className="tablewrap">
              <table>
                <thead><tr>{s.table.columns.map((c) => <th key={c}>{c}</th>)}</tr></thead>
                <tbody>
                  {s.table.rows.map((row, i) => (
                    <tr key={i}>{row.map((cell, j) => <td key={j} className="wrap-text"><Rich text={cell} /></td>)}</tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
          {s.bullets.length > 0 && <Bullets items={s.bullets} />}
        </div>
      ))}

      {n.corporate.length > 0 && (
        <>
          <h2 className="rh">Corporate news</h2>
          <ul className="obs">
            {n.corporate.map((c, i) => (
              <li key={i}>
                <strong>
                  {c.stock_code ? <Link to={`/company/${encodeURIComponent(c.stock_code)}`}>{c.company}</Link> : c.company}
                </strong>
                {c.stock_code && <span className="muted"> ({c.stock_code})</span>}: {c.headline}.{" "}
                <span className="muted"><Rich text={c.detail} /></span>
                {c.source_url && /^https?:\/\//.test(c.source_url) && (
                  <> <a href={c.source_url} target="_blank" rel="noopener noreferrer" className="small">source</a></>
                )}
              </li>
            ))}
          </ul>
        </>
      )}
    </>
  );
}

const ANNUAL_SHOWN = 20;

function AnnualReports({ items, days }: { items: Deadline[]; days: number }) {
  const [all, setAll] = useState(false);
  if (!items.length) return <p className="muted">No annual reports due in the next {days} days.</p>;
  return (
    <>
      <DeadlineTable rows={all ? items : items.slice(0, ANNUAL_SHOWN)} />
      {items.length > ANNUAL_SHOWN && (
        <button className="chip" style={{ marginTop: 8 }} onClick={() => setAll(!all)}>
          {all ? "Show fewer" : `Show all ${items.length}`}
        </button>
      )}
    </>
  );
}

function DeadlineTable({ rows }: { rows: Deadline[] }) {
  return (
    <div className="tablewrap">
      <table>
        <thead><tr><th>Due</th><th>Company</th><th>Filing</th><th>Last year</th><th /></tr></thead>
        <tbody>
          {rows.map((d) => (
            <tr key={`${d.stock_code}-${d.kind}-${d.period_end}`}>
              <td>{shortDate(d.due)}</td>
              <td className="name"><Link to={`/company/${d.stock_code}`}>{d.name}</Link> <span className="muted">{d.stock_code}</span></td>
              <td>{d.label}</td>
              <td className="muted wrap-text small">{d.context ?? "–"}</td>
              <td>{d.on_file && <span className="pill pass">filed</span>}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
